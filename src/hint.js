/**
 * 系统提示里的常驻提示：告诉模型「本插件存在，怎么用」。
 *
 * ## 为什么需要这段
 *
 * 归档目录注入在 **runtime context 消息的末尾**（`systemPrompt.context`），
 * 前面压着工作目录、文件策略、审批状态、checkout 路径、GUI URL 等宿主信息。
 *
 * 实测（2026-10-30）：模型两次看到那段文字都没有注意到目录——因为它被
 * 归进了「环境信息，跳过」的默认判断。没有提示就不会主动 `memory_search`。
 *
 * 这段提示放在**系统提示**里，每轮完整读取，位置显著。
 *
 * ## 为什么内容必须完全静态
 *
 * 系统提示在请求最前面，**改动一个字节就是全量前缀缓存失效**。
 * 所以这里**不能出现**归档数量、ID、时间、任何会话相关信息。
 * 动态信息全部留给 runtime context 里的目录。
 *
 * 静态的代价是几百字符/轮；缓存失效的代价是整份上下文重算，高几个数量级。
 * @module dsh-smart-context/hint
 */

/**
 * 系统提示里的常驻提示文本。
 *
 * **必须逐字节确定**：不依赖会话、时间、归档数量。
 */
export const CATALOG_HINT = [
  "本会话可能包含**已被宿主压缩遮蔽**的历史原文，这些内容已不在当前上下文中。",
  "",
  "若你需要对话早期的具体细节——报错码、文件路径、某个数值、某个已被推翻的结论——",
  "而当前上下文里没有，**不要猜，先检索**：",
  "",
  "- `memory_search({ query })` —— 按关键词找位置，返回归档 id 与命中片段",
  "- `memory_open({ id, cursor })` —— 分页取回原文",
  "",
  "可检索的归档清单列在**本轮运行上下文（runtime context）的末尾**，",
  "以「本会话有 N 份已归档的历史内容」开头。该清单只列出部分条目，",
  "但 `memory_search` 会搜索**全部**归档。",
  "",
  "检索是**字面匹配**：中文连续子串、英文大小写不敏感、多词 AND、引号内为精确短语。",
  "不支持同义改写、不做词干还原。零结果时请换一个更接近原文的词重试。",
].join("\n");

/**
 * 判断是否应该注入提示。
 *
 * **始终返回 true。** 保留这个函数是为了让「常驻」这个决定显式可查，
 * 而不是散落在调用处。
 *
 * 曾考虑「只在有归档时显示」，但那会让提示内容随归档数变化，
 * 每次变化都破坏系统提示的前缀缓存。常驻更划算。
 *
 * @returns {boolean}
 */
export function shouldShowHint() {
  return true;
}
